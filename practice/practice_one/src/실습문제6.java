public class 실습문제6 {
    static void main(String[] args) {
        System.out.println(2 + 3 * 4);
        //14
        System.out.println((2 + 3) * 4);
        //20
        System.out.println(10 - 2 + 3);
        //11
        int a = 5;
        System.out.println(a > 3 && a < 10);
        //true
        System.out.println(true || false && false);
        //true

    }
}
